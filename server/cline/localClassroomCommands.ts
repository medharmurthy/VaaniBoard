import { normalizeIndicText, detectBoardLanguage } from '../../utils/indicNormalize';
import { getChapterExercises } from '../rag/index';
import { generateMathPractice } from '../fln/mathPractice';
/** Explicit deterministic classroom mode. Never masquerades as a Cline/model response. */
export function resolveLocalClassroomCommand(req: any) {
  const prompt = normalizeIndicText(req.prompt.split('[USER MESSAGE]:').at(-1) || req.prompt);
  const lang = detectBoardLanguage(prompt) || req.boardLanguage || req.lang || 'hi';
  if (/student|doubt|sawaal|sawal|puch raha|छात्र|शंका|bachche ka|बच्चे का/i.test(prompt)) return null;
  let type: string; let config: any;
  let citations: any[] = [];
  const arithmetic = /addition|जोड़|\badd\b|subtraction|घटाव/.test(prompt) && /quiz|practice|questions|क्विज|अभ्यास/.test(prompt);
  if (/exercise|abhyas|अभ्यास/.test(prompt) && !arithmetic) {
    if (!req.activeChapter) return {functionCalls:[],textResponse:'Select a chapter in Classroom tools to bring up its exercises.',engine:'local',citations:[],proposals:[]};
    const items = getChapterExercises(req.activeChapter);
    if (!items.length) return {functionCalls:[],textResponse:'No exercises indexed for this chapter. Run npm run ingest:syllabus, or select another chapter.',engine:'local',citations:[],proposals:[]};
    type = 'EXERCISE_SHEET'; config = {title:items[0].chapterTitle,items,source:`NCERT Class 9 ${items[0].subject}`,lang:'en'};
    citations = items.slice(0,3).map(h=>({id:h.id,chapterTitle:h.chapterTitle,page:h.page,bookCode:h.bookCode}));
  } else if (arithmetic) {
    const max = Math.max(2, Math.min(100, Number(prompt.match(/(\d+)\s*(?:tak|तक)/)?.[1] || 20)));
    type = 'QUIZ_APP'; config = {title:lang === 'hi' ? 'जोड़-घटाव का अभ्यास' : 'Arithmetic practice',questions:generateMathPractice({op:/subtraction|घटाव/.test(prompt)?'sub':'add',max,count:10,lang}),lang};
  } else if (/counting|गिनती|গণনা/.test(prompt)) {
    type = 'COUNTING_ACTIVITY'; config = {title:lang === 'hi' ? 'आम गिनें' : 'Count mangoes',lang,min:1,max:10};
  } else if (/swar|vyanjan|स्वर|व्यंजन/.test(prompt) && /game|खेल|sikha/.test(prompt)) {
    if (lang !== 'hi') return null;
    type = 'LETTER_GAME'; config = {title:'स्वर और व्यंजन',lang:'hi',mode:'sort'};
  } else return null;
  return {functionCalls:[{name:'add_component',args:{componentType:type,gridPosition:'CENTER',configJson:JSON.stringify(config)}}],
    textResponse:req.lang === 'hi' ? 'स्थानीय गतिविधि तैयार है। यह AI मॉडल से नहीं बनाई गई है।' : 'Local classroom activity ready (deterministic, not generated by an AI model).',
    citations,proposals:[],engine:'local',provider:'local',model:'deterministic',events:['local-classroom-tool']};
}